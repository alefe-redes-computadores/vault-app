const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const Module = require('node:module');
const source = fs.readFileSync('lib/sync/medication-pull-links.ts', 'utf8');
const js = ts.transpile(source, { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 });
const mod = new Module('medication-pull-links'); mod._compile(js, 'medication-pull-links.js');
const preserve = mod.exports.preserveMedicationTreatmentLinks;
const remote = { id:'m',user_id:'u',person_id:'p',nome:'Novo' };
const local = { id:'m',user_id:'u',person_id:'p',tratamento_ids:['t'] };
assert.deepEqual(preserve(remote,local).tratamento_ids,['t']);
assert.equal(preserve(remote,local).nome,'Novo');
assert.equal(preserve(remote,{...local,user_id:'outro'}).tratamento_ids,undefined);
assert.equal(preserve(remote,{...local,person_id:'outra'}).tratamento_ids,undefined);
assert.equal(preserve(remote,undefined).tratamento_ids,undefined);
assert.deepEqual(preserve(remote,{...local,tratamento_ids:[]}).tratamento_ids,[]);
assert.deepEqual(local.tratamento_ids,['t']);
const pull = fs.readFileSync('lib/sync/pull.ts','utf8');
assert.match(pull,/mapRemote: preserveMedicationTreatmentLinks/);
assert.match(pull,/hasPendingOperation\(\s*"medicamentos"/);
console.log('M75 tratamento: importação preserva vínculos da mesma pessoa e conta.');
