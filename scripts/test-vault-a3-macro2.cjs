#!/usr/bin/env node
'use strict';
/** A3 MACRO2: real pure models + source contracts; synthetic owners only, no writes. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const ts=require('typescript');
const vm=require('node:vm');
let n=0;
function check(actual,description){assert.ok(actual,'A3 MACRO2: '+description);n++;}
function load(file,deps={}){
 const source=fs.readFileSync(file,'utf8');
 const kind=file.endsWith('.tsx')?ts.ScriptKind.TSX:ts.ScriptKind.TS;
 const tree=ts.createSourceFile(file,source,ts.ScriptTarget.Latest,true,kind);
 check(tree.parseDiagnostics.length===0,file+' source syntax');
 const converted=ts.transpileModule(source,{fileName:file,reportDiagnostics:true,compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX}});
 check(!converted.diagnostics?.some(d=>d.category===ts.DiagnosticCategory.Error),file+' transpile diagnostics');
 const module={exports:{}};
 const scope={module,exports:module.exports,Date,Set,Map,Array,Number,Error,console,require:(x)=>{if(!(x in deps))throw new Error('fixture import not resolved '+x);return deps[x];}};
 vm.runInNewContext(converted.outputText,scope,{filename:file});return module.exports;
}
const own='a-owner',person='a-person',other='b-owner',med='medicine';
const renewal=(id,date,more={})=>({id,user_id:own,person_id:person,medicamento_id:med,data:date,quantidade:null,preco:null,tipo_aquisicao:null,data_aquisicao:null,...more});
const renewalEvent=load('lib/health-supply/renewal-event.ts');
const v=load('lib/health-supply/a3-canonical-versions.ts',{'@/lib/health-supply/renewal-event':renewalEvent});
const rx1=renewal('r1','2026-03-01'),rx2=renewal('r2','2026-04-01'),rx3=renewal('r3','2026-05-01'),independent=renewal('u','2026-03-05');
const purchase=renewal('buy','2026-03-02',{quantidade:12,tipo_aquisicao:'comprado',data_aquisicao:'2026-03-02'});
const link=(id,before,after,more={})=>({id,renovacao_anterior_id:before,renovacao_atual_id:after,medicamento_id:med,user_id:own,person_id:person,tipo:'renovacao',deleted_at:null,...more});
const links=[link('l1','r1','r2'),link('l2','r2','r3')];
const inv=[rx1,rx2,rx3,independent,purchase];
const history=v.prescriptionHistoryA3(inv,links,own,person,med);
check(history.length===4,'acquisition never enters prescription timeline');
check(history.find(x=>x.id==='r1')?.version===1,'first canonical version');
check(history.find(x=>x.id==='r2')?.version===2,'second canonical version');
check(history.find(x=>x.id==='r3')?.version===3,'third canonical version');
check(history.find(x=>x.id==='u')?.version===null,'unlinked historic receipt has no invented version');
check(history.find(x=>x.id==='r1')?.superseded===true,'explicit prior prescription is superseded');
check(history.find(x=>x.id==='r3')?.superseded===false,'last event remains un-superseded');
check(history.find(x=>x.id==='r3')?.previousId==='r2','previous ID is A1 link');
check(v.prescriptionCandidatesA3(inv,links,own,person,med).map(x=>x.id).join(',')==='r3,u','only independent/newest prescriptions eligible');
check(v.prescriptionHistoryA3(inv,[],own,person,med).every(x=>x.version===null),'without A1 links no invented versions');
check(v.prescriptionHistoryA3(inv,[...links,link('foreign','r3','u',{user_id:other})],own,person,med).find(x=>x.id==='u').version===null,'cross-account link ignored');
check(v.prescriptionCandidatesA3(inv,[link('deleted','r3','u',{deleted_at:'2026-06-01'})],own,person,med).length===4,'deleted link ignored');
check(v.prescriptionHistoryA3([...inv,renewal('foreign','2026-02-01',{person_id:'other'})],[],own,person,med).length===4,'cross-person Rx excluded');
check(v.prescriptionCandidatesA3(inv,[],other,person,med).length===0,'cross-account candidate excluded');
check(v.prescriptionCandidatesA3(inv,[],own,other,med).length===0,'cross-person candidate excluded');
check(v.prescriptionCandidatesA3(inv,[],own,person,'different-med').length===0,'medication scoping');
const corrupted=[link('cycleA','r2','r1'),link('cycleB','r1','r2')];
check(v.prescriptionHistoryA3(inv,corrupted,own,person,med).find(x=>x.id==='r1').version===null,'cycle cannot fabricate a version');
const loc=load('lib/health-supply/a3-historical-locations.ts');
const pharmacy={id:'farm1',user_id:own,nome:'Farmácia antiga',endereco:'Rua A, 10'};
const place={id:'ub1',user_id:own,nome:'UBS',endereco:'Rua B'};
const moment='2026-11-20T12:00:00.000Z';
const s=loc.captureHistoricalLocationA3({userId:own,pharmacyId:'farm1',pharmacy,now:moment});
check(s.pharmacyName==='Farmácia antiga'&&s.pharmacyAddress==='Rua A, 10','name and address captured at the factual event');
check(s.recordedAt===moment&&s.source==='event','recordedAt preserved');
check(s.placeId===null,'no fictitious secondary location');
pharmacy.nome='Farmácia renomeada';
check(loc.locationDisplayA3(s,pharmacy.nome).name==='Farmácia antiga','historic snapshot immune to directory rename');
check(loc.locationDisplayA3(null,pharmacy.nome).historical===false,'legacy name clearly not historic');
check(loc.locationDisplayA3(s,pharmacy.nome).historical===true,'stored snapshot is labelled historic');
check(loc.captureHistoricalLocationA3({userId:own,now:moment})===null,'missing site cannot fabricate a snapshot');
check(loc.captureHistoricalLocationA3({userId:own,placeId:'ub1',place,now:moment})?.placeName==='UBS','health location snapshot captured');
assert.throws(()=>loc.captureHistoricalLocationA3({userId:other,pharmacyId:'farm1',pharmacy,now:moment}),/não pertence/);n++;
assert.throws(()=>loc.captureHistoricalLocationA3({userId:other,placeId:'ub1',place,now:moment}),/não pertence/);n++;
assert.throws(()=>loc.captureHistoricalLocationA3({userId:own,pharmacyId:'missing',pharmacy,now:moment}),/não pertence/);n++;
const earlier=JSON.stringify(s);
const changed=loc.recordLocationChangeA3({previous:s,next:null,history:[],now:'2026-11-21T12:00:00Z',reason:'historical_correction'});
check(changed.changed===true&&changed.history.length===1,'a factual correction is append-only');
check(JSON.stringify(s)===earlier,'original event snapshot is not mutated');
check(changed.history[0].before.pharmacyName==='Farmácia antiga','before snapshot preserved');
check(changed.snapshot===null,'explicit clearing is not a silent fallback');
check(loc.recordLocationChangeA3({previous:s,next:s,history:changed.history,now:moment,reason:'reassignment'}).changed===false,'same site is idempotent');
assert.throws(()=>loc.recordLocationChangeA3({previous:s,next:null,history:Array(200).fill(changed.history[0]),now:moment,reason:'historical_correction'}),/revisado/);n++;
for(const path of ['lib/health-supply/a3-continuity.ts','components/saude/SupplyContinuityA3.tsx','lib/repositories/renovacoes.ts','lib/repositories/retiradas.ts','lib/clinical-a1/repository.ts','app/saude/renovacao/nova-receita/page.tsx']){
 const code=fs.readFileSync(path,'utf8');
 const tree=ts.createSourceFile(path,code,ts.ScriptTarget.Latest,true,path.endsWith('.tsx')?ts.ScriptKind.TSX:ts.ScriptKind.TS);
 check(tree.parseDiagnostics.length===0,'edited '+path+' has valid TS/TSX syntax');
}
const repo=fs.readFileSync('lib/repositories/renovacoes.ts','utf8');
const a1=fs.readFileSync('lib/clinical-a1/repository.ts','utf8');
const form=fs.readFileSync('app/saude/renovacao/nova-receita/page.tsx','utf8');
const withdrawals=fs.readFileSync('lib/repositories/retiradas.ts','utf8');
const queue=fs.readFileSync('hooks/useSyncQueue.ts','utf8');
const pull=fs.readFileSync('lib/sync/pull.ts','utf8');
const sql=fs.readFileSync('supabase/migrations/20261120_a3_canonical_prescription_lineage_historical_locations.sql','utf8');
check(repo.includes('db.a1_prescription_links')&&repo.includes('clinicalA1Repository.linkPrescriptions'),'A1 link in existing canonical renewal transaction');
check(repo.includes('previousPrescriptionId')&&repo.includes('somenteReceita')&&repo.includes('countedCurrentStock'),'receipt/acquisition stock boundary preserved');
check(form.includes('previousPrescriptionA3')&&form.includes('prescriptionCandidatesA3'),'one existing receipt form integrates A1 history');
check(!/<select\b/.test(form),'A3 does not introduce visible native select into the receipt form (V112)');
check(form.includes('title="Vincular receita anterior"') && form.includes('title="Tipo de vínculo da receita"'), 'both receipt selectors reuse the accessible premium HealthRelationPicker');
check(form.includes('id="a3-prior-prescription"') && form.includes('id="a3-link-type"'), 'both A3 selector labels target real focusable controls');
check(form.includes('onValueChange={setPreviousPrescriptionA3}') && form.includes('setLinkTypeA3(value as "renovacao" | "substituicao")'), 'receipt picker writes only the controlled selection');
check(a1.includes('renovacao_anterior_id===input.previousId')&&a1.includes('renovacao_atual_id===input.currentId'),'A1 guards both sides of version graph');
check(withdrawals.includes('recordLocationChangeA3')&&withdrawals.includes('current.status!=="agendada"'),'completed withdrawal reassignment blocked');
check(queue.includes('a3_location_snapshot:r.a3_location_snapshot')&&queue.includes('a3_location_snapshot:renovacao.a3_location_snapshot'),'same offline-to-Supabase writer preserves snapshots');
check(pull.includes('"renovacoes"')&&pull.includes('"retiradas"')&&pull.includes('.select("*")'),'canonical pull handles additive columns');
const sqlExecutable=sql.replace(/--[^\n]*/g,'');
check(!/CREATE\s+TABLE/i.test(sqlExecutable)&&!/(DROP\s+TABLE|SECURITY\s+DEFINER|TRUNCATE)/i.test(sqlExecutable),'migration adds columns only, no parallel tables');
check(sql.includes('vault_a3_one_active_prescription_successor_uidx'),'Postgres enforces one active successor across devices');
check(sql.includes('ADD COLUMN IF NOT EXISTS a3_location_snapshot'),'snapshot migration idempotent');
check(!repo.includes('CREATE TABLE')&&!withdrawals.includes('CREATE TABLE'),'existing repositories remain authorities');
console.log(`VAULT_A3_MACRO2_TESTES_OK | ${n} guarantees: A1 canonical, historic events, privacy, sync, stock, UI, SQL`);
