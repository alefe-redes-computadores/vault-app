const assert=require('node:assert/strict');
const fs=require('node:fs');
const read=p=>fs.readFileSync(p,'utf8');
const summary=read('components/saude/ClinicalListSummary.tsx');
const group=read('components/saude/ClinicalCollectionGroup.tsx');
const filters=read('components/list/ListFilters.tsx');
const search=read('components/list/ListSearch.tsx');
