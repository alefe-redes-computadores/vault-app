const assert=require('node:assert/strict');
const fs=require('node:fs'), path=require('node:path'), Module=require('node:module'), ts=require('typescript');
const filename=path.resolve('lib/health-supply/notification-copy.ts');
const m=new Module(filename,module);
m._compile(ts.transpileModule(fs.readFileSync(filename,'utf8'),{fileName:filename,compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText,filename);
const {formatSupplyDeadline,supplyPreparationMessage:copy}=m.exports;
assert.equal(formatSupplyDeadline('2026-10-16'),'16/10/2026');
assert.equal(formatSupplyDeadline('2026-02-30'),'data não informada');
assert.equal(formatSupplyDeadline('not-a-date'),'data não informada');
assert.match(copy({processTitle:'Depressão',deadline:'2026-10-16',missing:['LME','Receita'],daysRemaining:1}),/Depressão · Preparar documentação até 16\/10\/2026\. Pendências: LME; Receita/);
assert.match(copy({processTitle:'',deadline:'2026-10-16',missing:[],daysRemaining:0}),/^Fornecimento · Preparar documentação hoje/);
assert.match(copy({processTitle:'Dor crônica',deadline:'2026-10-16',missing:['LME','Receita','Formulário'],daysRemaining:-1}),/atrasada.*Formulário/);
const source=fs.readFileSync('lib/health-intelligence/supply-insights.ts','utf8');
assert(source.includes('supplyPreparationMessage({'),'Brain must use centralized copy');
assert(!source.includes('prazo registrado para ${cycle.preparar_ate}'),'raw date regression');
assert(source.includes('ciclo_id=${encodeURIComponent(cycle.id)}'),'cycle deep link must remain');
assert(source.includes('fornecimento-planejamento-v103-${p.id}-${cycle.id}-${cycle.preparar_ate}'),'idempotent identity unchanged');
const health=fs.readFileSync('app/saude/minha-saude/page.tsx','utf8');
assert(health.includes('aria-label="Explorar dados de saúde por região"'),'Missing body-region contextual links');
for(const key of ['sono','frequencia_cardiaca','peso','caminhada'])assert(health.includes(`setMetric('${key}')`),key);
console.log('V157: data BR, pendências reais, contexto, link e identidade preservados');
