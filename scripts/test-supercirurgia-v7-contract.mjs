import fs from "node:fs";
const read = (path) => fs.readFileSync(path, "utf8");
let count = 0;
const ok = (condition, label) => { if (!condition) throw new Error(`FALHOU: ${label}`); count++; console.log(`OK: ${label}`); };
const types = read("lib/types.ts");
const repo = read("lib/repositories/doseLogs.ts");
const hook = read("hooks/useDoseLogs.ts");
const sync = read("hooks/useSyncQueue.ts");
const db = read("lib/db/index.ts");
const today = read("app/hoje/page.tsx");
const modal = read("components/saude/QuickDoseModal.tsx");
const reminders = read("app/saude/lembretes/page.tsx");
const hydration = read("app/saude/hidratacao/page.tsx");
const nav = read("components/BottomNav.tsx");
const brain = read("lib/health-insights.ts");
const migration = read("supabase/migrations/20260912_add_dose_log_origin.sql");
ok(types.includes('dose_kind?: "scheduled" | "sos" | "extra"'), "DoseLog diferencia programada, SOS e extra");
ok(repo.includes('doseKind?: "sos" | "extra"') && repo.includes('dose_kind:'), "repository cria evento extra independente");
ok(hook.includes('"sos" | "extra"') && hook.includes("doseKind,"), "hook expõe origem sem contornar repository");
ok(sync.includes("dose_kind:") && sync.includes("motivo:"), "push envia origem e contexto");
ok(db.includes("this.version(39)"), "Dexie v39 é aditiva");
ok(migration.includes("add column if not exists dose_kind") && migration.includes("dose_logs_dose_kind_check"), "migration Supabase é aditiva e validada");
ok(modal.includes("Registrar dose extra") && modal.includes("Corrigir existente"), "modal exige decisão quando o slot já existe");
ok(today.includes('log.dose_kind === "extra"') && today.includes('"Compromisso concluído"'), "Hoje distingue dose extra e compromisso concluído");
ok(!reminders.includes("<select"), "Lembretes não usa select nativo");
ok(hydration.includes("Meta diária opcional") && hydration.includes("Dias sem registro não são tratados"), "Hidratação melhora UX sem converter ausência em zero");
ok(nav.includes("relative isolate") && !nav.includes('layoutId="active-pill"'), "BottomNav isola o indicador ativo");
ok(brain.includes("doses-extras-") && brain.includes("Fonte interna: histórico de doses da pessoa ativa"), "cérebro descreve doses extras com fonte e período");
console.log(`CONTRATOS SUPERCIRURGIA V7: OK (${count})`);
