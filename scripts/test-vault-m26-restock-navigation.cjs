const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const { Module } = require('node:module');
const file = 'lib/health-intelligence/medication-restock-navigation.ts';
const source = fs.readFileSync(file, 'utf8');
const js = ts.transpileModule(source, {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const mod = new Module(file, module); mod.filename = file; mod.paths = module.paths; mod._compile(js, file);
const {medicationRestockHref, isRestockDestination} = mod.exports;
const id = 'med /?&á';
const href = medicationRestockHref(id, '/saude/medicamentos?filtro=sos');
const parsed = new URL(href, 'https://vault.invalid');
assert.equal(parsed.pathname, '/saude/renovacao/nova');
assert.equal(parsed.searchParams.get('medicamento_id'), id);
assert.equal(parsed.searchParams.get('mode'), 'acquisition');
assert.equal(parsed.searchParams.get('return_to'), '/saude/medicamentos?filtro=sos');
assert.equal(isRestockDestination(href, id), true);
assert.equal(isRestockDestination(href, 'outro'), false);
assert.equal(isRestockDestination('/saude/renovacao/nova-receita?medicamento_id='+encodeURIComponent(id), id), false);
assert.equal(isRestockDestination(undefined, id), false);
console.log('M26: navegação de reposição conserva identidade, retorno e separação de receita.');
