const read = path => fs.readFileSync(path,"utf8");
function compile(file) {
  const source = read(file);
  const tree = ts.createSourceFile(file,source,ts.ScriptTarget.Latest,true,file.endsWith("tsx")?ts.ScriptKind.TSX:ts.ScriptKind.TS);
  check(tree.parseDiagnostics.length===0,`sintaxe ${file}`);
  const result=ts.transpileModule(source,{fileName:file,reportDiagnostics:true,compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022,jsx:ts.JsxEmit.ReactJSX}});
  check((result.diagnostics||[]).every(x=>x.category!==ts.DiagnosticCategory.Error),`transpilação ${file}`);
  return result.outputText;
}
function load(file,mocks={}) {
  const mod=new Module(path.resolve(file),module);mod.filename=path.resolve(file);
  mod.require=id=>Object.prototype.hasOwnProperty.call(mocks,id)?mocks[id]:require(id);
  mod._compile(compile(file),mod.filename);
  return mod.exports;
}
