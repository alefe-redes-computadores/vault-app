function load(rel, overrides={}) {
  const file=path.join(root,rel),source=fs.readFileSync(file,'utf8');
  const compiled=ts.transpileModule(source,{fileName:file,compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX},reportDiagnostics:true});
  const errors=(compiled.diagnostics||[]).filter(d=>d.category===ts.DiagnosticCategory.Error);
  assert.deepEqual(errors.map(d=>ts.flattenDiagnosticMessageText(d.messageText,' ')),[],`${rel} syntax`);
  const mod=new Module(file,module);mod.filename=file;
  mod.require=id=>{
    if(Object.hasOwn(overrides,id))return overrides[id];
    throw new Error(`V228 Unexpected dependency ${rel} -> ${id}`);
  };
  mod._compile(compiled.outputText,file);return mod.exports;
}
