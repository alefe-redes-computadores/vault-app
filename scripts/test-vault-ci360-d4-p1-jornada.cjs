#!/usr/bin/env node
'use strict';
/** D4 P1 hermetic contract. No DB, network, private or clinical IO. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const Module=require('node:module');
const ts=require('typescript');
const root=path.resolve(__dirname,'..');
let checks=0;
const ok=(yes,why)=>{assert.ok(yes,'D4 P1: '+why);console.log('✓ D4 '+(++checks)+': '+why)};
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8');
function load(p,imports={}){
  const file=path.join(root,p),source=read(p);
  const compiled=ts.transpileModule(source,{fileName:file,compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022,jsx:ts.JsxEmit.ReactJSX},reportDiagnostics:true});
  ok(!(compiled.diagnostics||[]).some(x=>x.category===ts.DiagnosticCategory.Error),'transpilação '+p);
  const m=new Module(file,module);m.filename=file;m.paths=Module._nodeModulePaths(path.dirname(file));
  m.require=(name)=>{if(Object.prototype.hasOwnProperty.call(imports,name))return imports[name];throw Error('Dependência de runtime não permitida: '+name)};
  m._compile(compiled.outputText,file);return m.exports;
}
const course=load('lib/health-supply/temporary-course.ts');
const d4=load('lib/clinical/temporary-course-journey-d4.ts',{'@/lib/health-supply/temporary-course':course});
const ui=read('components/saude/TemporaryCourseJourneyD4.tsx');
const card=read('components/saude/TemporaryCourseMedicationCard.tsx');
const gate=read('scripts/test-v63-release-gate.mjs');
const m59=read('scripts/test-vault-m59-medication-journey.cjs');
const note=(start,days)=>`Tratamento temporário · ${start} · ${days} dia(s)`;
const NOTE=note('2026-11-17',7),MED='med-1',KEY=MED+'|'+NOTE;
const row=(date,time='09:00',overrides={})=>({id:date+'-'+time,user_id:'u1',person_id:'p1',medicamento_id:MED,dose_kind:'planned',motivo:NOTE,data:date,horario:time,...overrides});
const build=(logs,today='2026-11-18',overrides={})=>d4.buildCourseJourneyD4({userId:'u1',personId:'p1',medicationId:MED,courseKey:KEY,today,logs,...overrides});
const normal=[row('2026-11-17','09:00',{tomado_em:'2026-11-17T09:00:00'}),row('2026-11-18'),row('2026-11-19')];
let r=build(normal);
ok(r!==null,'retorna período canônico da pessoa ativa');
ok(r.currentDay===2&&r.totalDays===7,'dia 2 de 7 sem calcular adesão');
ok(r.phase==='within_period','fase dentro do prazo informado');
ok(r.start==='2026-11-17'&&r.through==='2026-11-23','duração atravessa dias sem deslocar fuso');
ok(r.confirmed===1&&r.ignored===0&&r.todayPending===1&&r.futurePending===1&&r.earlierPending===0,'separa tomado / hoje / futuro');
ok(r.scheduled===3,'total vem de DoseLogs observados, não de doses inferidas');
ok(d4.courseJourneyCaptionD4(r)==='Dia 2 de 7 do período informado','rótulo claro e sem conclusão inferida');
ok(build(normal,'2026-11-16').phase==='future','período futuro não vira tratamento iniciado');
ok(build(normal,'2026-11-24').phase==='period_elapsed','prazo superado não implica conclusão');
ok(d4.courseJourneyCaptionD4(build(normal,'2026-11-24')).includes('não confirma a conclusão'),'texto não afirma finalização');
ok(build([row('2026-11-17')],'2026-11-20').earlierPending===1,'horário anterior sem decisão não vira não adesão');
ok(build([row('2026-11-17','09:00',{ignorado_em:'2026-11-17T10:00:00'})],'2026-11-18').ignored===1,'ignorado explícito preservado');
ok(build([row('2026-11-17','09:00',{tomado_em:'2026-11-17T09:00:00'})],'2026-11-24').confirmed===1,'tomada histórica preservada após prazo');
ok(build([row('2026-11-17','09:00',{tomado_em:'t',ignorado_em:'i'})]).conflicted,'tomado e ignorado no mesmo log pede revisão');
ok(build([row('2026-11-17'),row('2026-11-17','09:00',{id:'duplicado'})]).conflicted,'slot duplicado sinalizado, sem exclusão');
ok(build([row('2026-11-45')]).conflicted,'data impossível não aceita como evento cronológico confiável');
ok(build([row('2026-11-17','25:99')]).conflicted,'horário inválido gera alerta');
ok(build([row('2026-11-25')]).conflicted,'slot fora do período informado sinalizado');
ok(build([row('2026-11-17')],'2026-02-30')===null,'data atual impossível recusa construção');
ok(build([row('2026-11-17')],'2026-11-18',{personId:'p2'})===null,'outra pessoa não herda curso');
ok(build([row('2026-11-17')],'2026-11-18',{userId:'u2'})===null,'outra conta não herda curso');
ok(build([row('2026-11-17')],'2026-11-18',{medicationId:'med-2'})===null,'outro medicamento não herda curso');
ok(build([row('2026-11-17')],'2026-11-18',{courseKey:'med-2|'+NOTE})===null,'chave de curso não corresponde ao medicamento');
ok(build([row('2026-11-17','09:00',{dose_kind:'sos'})])===null,'SOS nunca vira tratamento prescrito');
ok(build([row('2026-11-17','09:00',{motivo:'Dose avulsa'})])===null,'avulsa não vira curso');
ok(build([row('2026-11-17','09:00',{person_id:'p2'})])===null,'DoseLog de outra pessoa excluído');
ok(build([row('2026-11-17','09:00',{user_id:'u2'})])===null,'DoseLog de outra conta excluído');
ok(build([row('2026-11-17','09:00',{medicamento_id:'med-2'})])===null,'DoseLog de outro medicamento excluído');
const leap=note('2028-02-28',3),lrow=row('2028-02-29','10:00',{motivo:leap});
r=build([lrow],'2028-02-29',{courseKey:MED+'|'+leap});
ok(r!==null&&r.currentDay===2&&r.through==='2028-03-01','29 fevereiro validado como dia 2 de 3 em ano bissexto');
const invalid=note('2026-02-30',3),bad=build([row('2026-03-01','10:00',{motivo:invalid})],'2026-03-01',{courseKey:MED+'|'+invalid});
ok(bad!==null&&bad.phase==='review_dates'&&bad.warning!==null,'nota de data inválida não vira prescrição válida');
const interval='Tratamento temporário · 2026-11-17 · 2 dia(s) · intervalo 8h · primeira 2026-11-17T08:00';
r=build([row('2026-11-18','08:00',{motivo:interval})],'2026-11-18',{courseKey:MED+'|'+interval});
ok(r!==null&&r.through==='2026-11-19'&&r.usesHourInterval&&r.currentDay===null,'intervalo preserva fim e não infere dia X sem horário atual');
ok(d4.courseJourneyCaptionD4(r).includes('Período por intervalo'),'intervalo tem legenda temporal honesta');
const crossMidnight='Tratamento temporário · 2026-11-17 · 1 dia(s) · intervalo 8h · primeira 2026-11-17T23:00';
r=build([row('2026-11-18','07:00',{motivo:crossMidnight})],'2026-11-18',{courseKey:MED+'|'+crossMidnight});
ok(r!==null&&r.through==='2026-11-18'&&r.usesHourInterval&&r.currentDay===null,
  'intervalo após 23h atravessa meia-noite sem falsa progressão diária');
ok(!ui.includes('medicamentosRepository')&&!ui.includes('db.')&&!ui.includes('supabase'),'painel D4 sem escrita local/remota');
ok(!read('lib/clinical/temporary-course-journey-d4.ts').includes('.update('),'domínio D4 puramente de leitura');
ok(ui.includes('Contagem de dias é calendário, não adesão'),'limitação clínica sempre visível');
ok(card.includes('<TemporaryCourseJourneyD4')&&card.includes('<CourseReviewM1'),'integração conserva acompanhamento humano M1');
ok(card.includes('TemporaryCourseMedicationCard')&&card.includes('temporaryCourseSummaries'),'card legado mantém identidade canônica');
ok((gate.match(/"scripts\/test-vault-ci360-d4-p1-jornada.cjs"/g)||[]).length===1,'contrato D4 único no V63');
ok(gate.includes('"scripts/test-vault-ci360-p6-p4d-catalogo.cjs"'),'P4-D publicada é requisito histórico');
ok(m59.includes("'@/components/saude/TemporaryCourseJourneyD4':{TemporaryCourseJourneyD4:()=>null}"),'M59 preserva testes legados e registra mock isolado do D4');
console.log(`D4 P1: ${checks} garantias direcionadas sem IO clínico.`);
