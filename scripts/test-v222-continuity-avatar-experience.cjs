const ts = require('typescript');
const read = path => fs.readFileSync(path, 'utf8');
function loadPure(path, mocks = {}) {
  const compiled=ts.transpileModule(read(path), {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
  const module={exports:{}};
  new Function('exports','module','require',compiled)(module.exports,module,id=>{
    if (Object.hasOwn(mocks,id)) return mocks[id];
    throw new Error(`Unexpected dependency ${id} in ${path}`);
  });
  return module.exports;
}
