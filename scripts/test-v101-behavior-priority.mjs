const ignored=analyze([...old,...[2,3,4,5,6].map(d=>row(d,0,'scheduled',true))]);
assert.equal(ignored.find(x=>x.id.includes('ignoradas')).comparacao.valorAtual,100,'ignoradas explícitas');
assert.equal(analyze([]).length,0,'ausência nunca vira falta');
const extraOld=old.slice(0,3).map(x=>({...x,dose_kind:'extra'})),extraCurrent=current.map(x=>({...x,dose_kind:'extra'}));
assert.equal(analyze([...extraOld,...extraCurrent]).find(x=>x.id.includes('extras')).comparacao.valorAtual,5,'extras comparadas como eventos');
