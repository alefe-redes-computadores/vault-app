import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import Module, { createRequire } from 'node:module';
const require=createRequire(import.meta.url);
const ts=require(process.env.VAULT_TEST_TYPESCRIPT || 'typescript');
const cache=new Map();
function load(relative) {
  const filename=path.resolve(relative);
  if(cache.has(filename))return cache.get(filename).exports;
  const mod=new Module(filename); cache.set(filename,mod);
  mod.filename=filename; mod.paths=Module._nodeModulePaths(path.dirname(filename));
  mod.require=(name)=>name.startsWith('@/')?load(name.slice(2)+'.ts'):name.startsWith('.')?load(path.resolve(path.dirname(filename),name)+'.ts'):require(name);
  mod._compile(ts.transpileModule(fs.readFileSync(filename,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText,filename);
  return mod.exports;
}
const {buildBehaviorInsights}=load('lib/health-intelligence/behavior-insights.ts');
const {compareHealthPriority,healthPriorityPresentation}=load('lib/health-intelligence/priority.ts');
const {reconcileBrainV5,brainV5Presentation}=load('lib/health-intelligence/brain-v5.ts');
const context={personId:'p',hoje:'2026-10-09',medicamentos:[{id:'m',nome:'Teste',person_id:'p',tipo_uso:'continuo',status:'ativo'}],doseLogs:[]};
const row=(day,delay=0,kind='scheduled',ignored=false)=>({id:`${day}-${kind}`,person_id:'p',medicamento_id:'m',data:`2026-10-${String(day).padStart(2,'0')}`,horario:'08:00',dose_kind:kind,...(ignored?{ignorado_em:`2026-10-${String(day).padStart(2,'0')}T08:00:00`}:{tomado_em:`2026-10-${String(day).padStart(2,'0')}T${delay?'09':'08'}:00:00`})});
const old=[26,27,28,29,30].map(d=>({...row(d),id:`old-${d}`,data:`2026-09-${d}`,tomado_em:`2026-09-${d}T08:00:00`}));
const current=[2,3,4,5,6].map(d=>row(d,60));
const analyze=(logs)=>buildBehaviorInsights({...context,doseLogs:logs});
assert.equal(analyze([...old,...current]).filter(x=>x.id.includes('horario')).length,1,'mudança recorrente detectada');
assert.equal(analyze([...old,...current.slice(0,2)]).length,0,'amostra pequena não sustenta tendência');
assert.equal(analyze([...old,...current.map(x=>({...x,person_id:'outra'}))]).length,0,'outra pessoa excluída');
assert.equal(analyze([...old,...current.map(x=>({...x,dose_kind:'extra'}))]).filter(x=>x.id.includes('horario')).length,0,'extra separado da rotina');
assert.equal(analyze([...old,...current,...current]).find(x=>x.id.includes('horario')).amostra,10,'duplicatas não aumentam confiança');
assert.equal(analyze([...old,...current.map(x=>({...x,tomado_em:undefined,created_at:'2026-10-08T10:00:00'}))]).length,0,'timestamp técnico não substitui tomada');
assert.equal(analyze([...old,...current.map(x=>({...x,data:'2026-10-09'}))]).length,0,'dia em curso fora da comparação');
