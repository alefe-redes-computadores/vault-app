function transpile(p){
  const source=read(p);
  const ast=ts.createSourceFile(p,source,ts.ScriptTarget.Latest,true,p.endsWith('.tsx')?ts.ScriptKind.TSX:ts.ScriptKind.TS);
  ok(ast.parseDiagnostics.length===0,`parser ${p}`);
  const out=ts.transpileModule(source,{fileName:p,reportDiagnostics:true,compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX}});
  ok(!(out.diagnostics||[]).some(x=>x.category===ts.DiagnosticCategory.Error),`transpile ${p}`);
  return out.outputText;
}
